#!/usr/bin/env python3
"""Rebuild the web dashboard files in all three sketch folders.

Run it after editing dashboard.html, barista_mesh.h, barista_web.h or barista_music.h:   python3 dashboard_src/build_assets.py
It writes dashboard_html.h (the page, gzipped) and copies barista_mesh.h, barista_web.h and barista_music.h into each
node's folder, because an Arduino sketch can only include files from its own folder.
"""
import gzip
import shutil
from pathlib import Path

SRC = Path(__file__).resolve().parent
NODES = ["node1_pump_station", "node2_control_center", "node3_output"]

gz = gzip.compress((SRC / "dashboard.html").read_bytes(), 9, mtime=0)  # mtime=0: same input, same output
rows = [",".join(str(b) for b in gz[i:i + 20]) for i in range(0, len(gz), 20)]
header = (
    "// GENERATED by dashboard_src/build_assets.py from dashboard_src/dashboard.html.\n"
    "// Do not edit by hand: change dashboard.html and run the script again.\n"
    "// The page is stored gzipped; browsers unpack it themselves.\n"
    "#ifndef DASHBOARD_HTML_H\n#define DASHBOARD_HTML_H\n\n"
    "const uint8_t DASHBOARD_HTML_GZ[] PROGMEM = {\n  " + ",\n  ".join(rows) + "\n};\n"
    f"const size_t DASHBOARD_HTML_GZ_LEN = {len(gz)};\n\n#endif\n"
)
for node in NODES:
    folder = SRC.parent / node
    (folder / "dashboard_html.h").write_text(header)
    for name in ("barista_mesh.h", "barista_web.h", "barista_music.h"):
        shutil.copyfile(SRC / name, folder / name)
    print(f"{node}: dashboard_html.h ({len(gz)} bytes gzipped), barista_mesh.h, barista_web.h, barista_music.h")
